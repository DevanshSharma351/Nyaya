"""Declarative base and shared column mixins."""

from __future__ import annotations

import uuid
from datetime import UTC, datetime
from typing import Any

from sqlalchemy import DateTime, MetaData, func
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Embedding width. Fixed at the dimension of the default embedding model
# (bge-m3, 1024). pgvector indexes require a static dimension, so switching
# embedding models is a migration, not a config change - see ADR-0003.
EMBEDDING_DIM = 1024

# Explicit naming convention so that Alembic emits stable, human-readable
# constraint names instead of database-generated ones. Without this, autogenerated
# migrations produce unnameable constraints that cannot later be dropped cleanly.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)

    type_annotation_map = {dict[str, Any]: JSONB}


class UUIDPrimaryKey:
    """UUID primary keys.

    Chosen over serial integers so that identifiers can be minted client-side
    before insertion (agents build object graphs in memory before persisting),
    and so that record counts are not inferable from an identifier.
    """

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )


class Timestamped:
    """Creation and modification times, maintained by the database."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=lambda: datetime.now(UTC),
        nullable=False,
    )


__all__ = ["Base", "EMBEDDING_DIM", "Timestamped", "UUIDPrimaryKey"]
