"""Declarative base and shared column mixins."""

from __future__ import annotations

import enum
import uuid
from datetime import UTC, datetime
from typing import Any, ClassVar

from sqlalchemy import DateTime, MetaData, String, TypeDecorator, func
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Embedding width. Fixed at the dimension of the default embedding model
# (bge-m3, 1024). pgvector indexes require a static dimension, so switching
# embedding models is a migration, not a config change - see ADR-0003.
EMBEDDING_DIM = 1024

# Explicit naming convention so that Alembic emits stable, human-readable
# constraint names instead of database-generated ones. Without this, autogenerated
# migrations produce unnameable constraints that cannot later be dropped cleanly.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class StrEnumType(TypeDecorator):
    """Store a `StrEnum` as text and return it as the enum member.

    Without this, a `Mapped[ApprovalStatus]` column stores correctly but loads as
    a plain `str`, so the type annotation is a lie and any caller reaching for
    `.value` on a loaded row raises `AttributeError`. The failure is silent until
    the exact line that touches it runs, which in this codebase would be a
    compliance decision path.

    `StrEnum` members compare equal to their string form, so equality checks kept
    working and hid the problem - the crash only appears on attribute access.
    """

    impl = String
    cache_ok = True

    def __init__(self, enum_class: type[enum.StrEnum], length: int = 32) -> None:
        self.enum_class = enum_class
        super().__init__(length=length)

    def process_bind_param(self, value: Any, dialect: Any) -> str | None:
        if value is None:
            return None
        return value.value if isinstance(value, enum.Enum) else str(value)

    def process_result_value(self, value: Any, dialect: Any) -> Any:
        if value is None:
            return None
        try:
            return self.enum_class(value)
        except ValueError:
            # A value written before the vocabulary changed. Returned as-is
            # rather than raising, so a historical record stays readable.
            return value


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)

    # Map bare `dict` annotations onto JSONB rather than SQLAlchemy's default
    # JSON, so that Postgres can index them (GIN) and query into them.
    type_annotation_map: ClassVar[dict] = {dict[str, Any]: JSONB}


class UUIDPrimaryKey:
    """UUID primary keys.

    Chosen over serial integers so that identifiers can be minted client-side
    before insertion (agents build object graphs in memory before persisting),
    and so that record counts are not inferable from an identifier.
    """

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)


class Timestamped:
    """Creation and modification times, maintained by the database."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=lambda: datetime.now(UTC),
        nullable=False,
    )


__all__ = ["EMBEDDING_DIM", "Base", "Timestamped", "UUIDPrimaryKey"]
